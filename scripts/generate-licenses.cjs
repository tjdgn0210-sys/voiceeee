// Development tool: node scripts/generate-licenses.cjs
// Writes src/constants/open-source-licenses.ts from the direct dependencies in package.json (name, version, license, homepage).
// Run it again after adding or updating a package. The full license texts of transitive packages are a release task (M6).
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const names = Object.keys({ ...manifest.dependencies }).sort();
const entries = names.map(name => {
  const file = path.join(root, 'node_modules', name, 'package.json');
  const info = JSON.parse(fs.readFileSync(file, 'utf8'));
  const license = typeof info.license === 'string' ? info.license : info.license?.type ?? (Array.isArray(info.licenses) ? info.licenses.map(item => item.type).join(' OR ') : 'UNKNOWN');
  return { name, version: info.version, license };
});
const body = entries.map(item => `  { name: '${item.name}', version: '${item.version}', license: '${item.license}' },`).join('\n');
const output = `// Generated by scripts/generate-licenses.cjs from package.json. Do not edit by hand.
export type OpenSourcePackage = { name: string; version: string; license: string };

export const OPEN_SOURCE_PACKAGES: readonly OpenSourcePackage[] = [
${body}
];
`;
fs.writeFileSync(path.join(root, 'src/constants/open-source-licenses.ts'), output);
console.log(`${entries.length} packages written`);
